import {
  parseAbilities,
  parseEncounters,
  parseForms,
  parseItems,
  parseMaps,
  parseMoves,
  parsePokemon,
} from "./parsers.ts";

export interface GeneratedData {
  files: Record<string, string>;
  counts: Record<string, number>;
  warnings: string[];
}

// Same filenames and export names consumed by apps/web. Missing optional
// expansions deliberately produce empty files so old content cannot survive.
export function generateData(pbs: Record<string, string>): GeneratedData {
  for (const required of [
    "pokemon.txt",
    "moves.txt",
    "items.txt",
    "abilities.txt",
  ]) {
    if (!pbs[required]?.trim())
      throw new Error(`PBS/${required} is missing or empty.`);
  }
  const combine = (pattern: RegExp) =>
    Object.keys(pbs)
      .filter((name) => pattern.test(name))
      .sort((a, b) => {
        // Load the base file first, then extensions in a stable order.
        const rank = (name: string) => (name.includes("_") ? 1 : 0);
        return rank(a) - rank(b) || a.localeCompare(b);
      })
      .map((name) => pbs[name])
      .join("\n");
  const normal = parsePokemon(pbs["pokemon.txt"], "normal");
  const absolution = parsePokemon(
    pbs["pokemon_absolution.txt"] || "",
    "absolution",
  );
  if (!normal.length)
    throw new Error(
      "PBS/pokemon.txt contains no publishable Pokémon sections.",
    );
  const bases = [...normal, ...absolution];
  const forms = parseForms(
    combine(/^pokemon_forms(?!_absolution).*\.txt$/i),
    "normal",
    bases,
  );
  const absolutionForms = parseForms(
    pbs["pokemon_forms_absolution.txt"] || "",
    "absolution",
    bases,
  );
  const moves = parseMoves(combine(/^moves(?:_.*)?\.txt$/i));
  const items = parseItems(
    combine(/^items(?!_absolution(?:\.|_))(?:_.*)?\.txt$/i),
    "normal",
  );
  const absolutionItems = parseItems(
    pbs["items_absolution.txt"] || "",
    "absolution",
  );
  const abilities = parseAbilities(combine(/^abilities(?:_.*)?\.txt$/i));
  const encounters = parseEncounters(pbs["encounters.txt"] || "");
  const maps = parseMaps(pbs["map_metadata.txt"] || "");
  const files: Record<string, string> = {};
  function emit(filename: string, type: string, name: string, value: unknown) {
    files[`src/data/${filename}.ts`] =
      `// Generated by Absolution Asset Studio.\nimport type { ${type} } from "@absolution/shared-types";\n\nexport const ${name}: ${type}[] = ${JSON.stringify(value, null, 2)};\n`;
  }
  emit("pokemon", "Fakemon", "fakemons", normal);
  emit("pokemon_absolution", "Fakemon", "fakemons", absolution);
  emit("pokemon_forms", "PokemonForm", "pokemonForms", forms);
  emit(
    "pokemon_forms_absolution",
    "PokemonForm",
    "pokemonForms",
    absolutionForms,
  );
  emit("moves", "Move", "moves", moves);
  emit("items", "Item", "items", items);
  emit("items_absolution", "Item", "items", absolutionItems);
  emit("abilities", "Ability", "abilities", abilities);
  files["src/data/encounters.ts"] =
    `// Generated by Absolution Asset Studio.\nimport type { EncountersData } from "@absolution/shared-types";\nexport type { EncounterEntry } from "@absolution/shared-types";\n\nexport const encountersData: EncountersData = ${JSON.stringify(encounters, null, 2)};\n`;
  files["src/data/maps.ts"] =
    `// Generated by Absolution Asset Studio.\nimport type { TileData } from "@absolution/shared-types";\n\nexport const tilesData: Record<string, TileData> = ${JSON.stringify(maps, null, 2)};\n`;
  const warnings = ["encounters.txt", "map_metadata.txt"]
    .filter((name) => !pbs[name])
    .map(
      (name) => `PBS/${name} is absent; its generated dataset will be empty.`,
    );
  return {
    files,
    warnings,
    counts: {
      Pokémon: bases.length,
      Forms: forms.length + absolutionForms.length,
      Moves: moves.length,
      Items: items.length + absolutionItems.length,
      Abilities: abilities.length,
      Maps: Object.keys(maps).length,
      "Encounter maps": Object.keys(encounters).length,
    },
  };
}
